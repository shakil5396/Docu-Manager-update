const express = require('express');
const multer = require('multer');
const auth = require('../controllers/authController');
const { requireAuth } = require('../middleware/auth');
const router = express.Router();
const avatarUpload = multer({ storage: multer.memoryStorage(), limits: { fileSize: 2 * 1024 * 1024, files: 1 }, fileFilter: (_req, file, done) => ['image/jpeg','image/png','image/webp'].includes(file.mimetype) ? done(null, true) : done(Object.assign(new Error('Choose a PNG, JPEG, or WebP image.'), { status: 400 })) });
router.get('/google', auth.googleStart);
router.get('/google/callback', auth.googleCallback);
router.post('/register', auth.register);
router.post('/login', auth.login);
router.post('/verify-email', auth.verifyEmail);
router.post('/resend-verification', auth.resendVerification);
router.post('/forgot-password', auth.forgotPassword);
router.post('/reset-password', auth.resetPassword);
router.get('/me', requireAuth, auth.me);
router.patch('/profile', requireAuth, auth.updateProfile);
router.get('/profile/avatar', requireAuth, auth.avatar);
router.post('/profile/avatar', requireAuth, avatarUpload.single('avatar'), auth.uploadAvatar);
router.delete('/profile/avatar', requireAuth, auth.removeAvatar);
router.patch('/password', requireAuth, auth.changePassword);
router.delete('/account', requireAuth, auth.deleteAccount);
router.post('/logout', requireAuth, auth.logout);
module.exports = router;
